frase = "Linguagem de Programação Python"

print("O caracter 8 da frase é:", frase[8])

#25 até 31 - só exibe até o 30
print(frase[25:31]) #exibindo Phyton

#até 18 -  exibe até o 17
print(frase[:18])#exibindo Linguagem de Progr

#18 até o final
print(frase[18:])#exibindo amação Python

#0 até 20 pulando de 2 em 2
print(frase[:20:2])

#0 até final
print(frase[::])

#0 até final pulando de 2 em 2
print(frase[::2])

#exibindo o último caracter
print(frase[-1])

#exibindo do -31 até o final
print(frase[-31:])

#-6 até final
print(frase[-6:])

#-5 até -2
print(frase[-5:-2])
